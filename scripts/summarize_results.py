"""Aggregates results/*/ into results/SUMMARY.md - the "presenting results"
gap identified alongside the rest of the logging/provenance work:
many run directories with no single place showing the actual headline numbers.

Groups runs by base name (stripping the `_seed<N>` suffix experiments/run.py's
own `--seed` override applies, run.py's main()), computes final/max accuracy
mean+-stdev across seeds within a group - the exact statistic this project has
been computing by hand (e.g. "mean=89.79%, stdev=0.107pp across 4 seeds"). Read-only: never modifies results/.

Usage:
    uv run scripts/summarize_results.py
    uv run scripts/summarize_results.py --root results --out results/SUMMARY.md
"""

from __future__ import annotations

import argparse
import json
import re
import statistics
from dataclasses import dataclass
from pathlib import Path

_SEED_SUFFIX = re.compile(r"_seed[A-Za-z0-9]+$")


@dataclass
class RunResult:
    name: str
    base_name: str
    seed: int | None
    final_accuracy: float
    max_accuracy: float
    verdict: str


def _load_run(run_dir: Path) -> RunResult | None:
    metrics_path = run_dir / "metrics.json"
    config_path = run_dir / "config.json"
    if not (metrics_path.exists() and config_path.exists()):
        return None

    metrics = json.loads(metrics_path.read_text())
    config = json.loads(config_path.read_text())
    accuracy = metrics.get("accuracy")
    if not accuracy:
        return None

    validation_path = run_dir / "validation_report.json"
    verdict = "UNKNOWN"
    if validation_path.exists():
        verdict = json.loads(validation_path.read_text()).get("overall_verdict", "UNKNOWN")

    return RunResult(
        name=run_dir.name,
        base_name=_SEED_SUFFIX.sub("", run_dir.name),
        seed=config.get("seed"),
        final_accuracy=accuracy[-1],
        max_accuracy=max(accuracy),
        verdict=verdict,
    )


def _mean_stdev(values: list[float]) -> tuple[float, float | None]:
    if len(values) == 1:
        return values[0], None
    return statistics.mean(values), statistics.stdev(values)


def summarize(root: Path) -> str:
    runs = sorted(
        (r for d in root.iterdir() if d.is_dir() and (r := _load_run(d)) is not None),
        key=lambda r: r.name,
    )

    groups: dict[str, list[RunResult]] = {}
    for run in runs:
        groups.setdefault(run.base_name, []).append(run)

    lines = [
        "# Results summary",
        "",
        (
            "Auto-generated by `scripts/summarize_results.py` - regenerate after new runs, "
            "do not hand-edit. See `results/MANIFEST.md` for which of these are the real, "
            "citable results versus exploratory/smoke runs."
        ),
        "",
        "| Group | Seeds | Final acc. (mean +- stdev) | Max acc. (mean +- stdev) | Verdicts |",
        "|---|---|---|---|---|",
    ]
    for base_name in sorted(groups):
        group = groups[base_name]
        final_mean, final_stdev = _mean_stdev([r.final_accuracy for r in group])
        max_mean, max_stdev = _mean_stdev([r.max_accuracy for r in group])
        final_str = f"{final_mean:.2f}%" + (f" +- {final_stdev:.3f}pp" if final_stdev else "")
        max_str = f"{max_mean:.2f}%" + (f" +- {max_stdev:.3f}pp" if max_stdev else "")
        verdicts = ", ".join(sorted({r.verdict for r in group}))
        lines.append(f"| `{base_name}` | {len(group)} | {final_str} | {max_str} | {verdicts} |")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default="results", help="Directory containing run subdirectories")
    parser.add_argument("--out", default=None, help="Write markdown here too (default: print only)")
    args = parser.parse_args()

    root = Path(args.root)
    report = summarize(root)
    print(report)

    if args.out:
        Path(args.out).write_text(report)


if __name__ == "__main__":
    main()
