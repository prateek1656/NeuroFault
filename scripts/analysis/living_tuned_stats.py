"""Living spares at the tuned rate: analysis exactly as pre-registered in
the living-spares tuned-rate pre-registration (L1-L4, n=3, labels only, noise thr 0.53).
Reads raw events.json from results/_live20; writes results/derived/living-tuned-results.md."""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from paper_stats import sign_p, wilcoxon_exact

SEEDS, THR = [42, 101, 102], 2 * 0.46 / math.sqrt(3)
ARMS = {"C": "frozen", "Cp": "living", "Cpo": "living_orig"}
OLD_CP = {42: 83.86, 101: 84.74, 102: 84.32}  # A4000 eta-0.5 C', different fault maps (Amendment 1)


def ev(arm: str, s: int) -> dict:
    d = json.loads(
        (ROOT / f"results/_live20/resnet9_tuned_c_{ARMS[arm]}_seed{s}/events.json").read_text()
    )
    assert d["complete"], (arm, s)
    return d


R = {a: {s: ev(a, s) for s in SEEDS} for a in ARMS}
checks = []
for s in SEEDS:
    h = [[w["fault_map_hash"] for w in R[a][s]["events"]] for a in ARMS]
    if not all(x == h[0] for x in h):
        checks.append(f"UNPAIRED seed {s}")
    st = {a: R[a][s]["summary"]["total_burst_batches"] for a in ARMS}
    if len(set(st.values())) != 1:
        checks.append(f"SANITY seed {s}: burst steps differ {st}")


def label(d: list[float]) -> str:
    m = sum(d) / len(d)
    if any(x > 0 for x in d) and any(x < 0 for x in d):
        return "MIXED"
    if m < 0 and not any(x > 0 for x in d):
        return "NEGATIVE"
    if abs(m) < THR:
        return "NOISE-LEVEL"
    return "CONSISTENT"


def comp(cid, a, b, key="final_test_acc"):
    d = [round(R[a][s]["summary"][key] - R[b][s]["summary"][key], 4) for s in SEEDS]
    m = sum(d) / 3
    sd = stats.tstd(d)
    pt = float(stats.ttest_1samp(d, 0).pvalue) if sd > 0 else float("nan")
    return {
        "id": cid,
        "a": a,
        "b": b,
        "key": key,
        "d": d,
        "mean": m,
        "sd": sd,
        "p_t": pt,
        "p_sign1": sign_p(d)[0],
        "p_wilc": wilcoxon_exact(d),
        "wins": sum(x > 0 for x in d),
        "label": label(d),
    }


rows = [
    comp("L1", "Cp", "C"),
    comp("L2", "Cpo", "C"),
    comp("L3", "Cp", "Cpo"),
    comp("L4", "Cp", "C", "lifetime_mean_test_acc"),
]
L1 = rows[0]
if L1["mean"] >= THR and L1["wins"] == 3:
    dec = "SUPPORTED"
elif L1["mean"] <= -THR and not any(x > 0 for x in L1["d"]):
    dec = "REVERSED"
elif abs(L1["mean"]) < THR or L1["label"] == "MIXED":
    dec = "NOT SUPPORTED"
else:
    dec = "NONE OF THE PRE-REGISTERED OUTCOMES"


def f(x, k=2):
    return "n/a" if isinstance(x, float) and math.isnan(x) else f"{x:.{k}f}"


md = (
    [
        "# Living spares at the tuned rate: results (2026-10-14)",
        "",
        (
            "Generated by `scripts/analysis/living_tuned_stats.py` from raw `results/_live20` (RTX 4060 Ti, Amendment 1). "
            "Rules: the living-spares tuned-rate pre-registration (registered before any counted run)."
        ),
        "",
        (
            f"**Decision (pre-registered): {dec}.** L1 C'-tuned minus C-tuned = {L1['mean']:+.2f} pt "
            f"(per seed {', '.join(f'{x:+.2f}' for x in L1['d'])}), label {L1['label']}, noise threshold {THR:.2f}."
        ),
        "",
        "## Checks",
        "",
    ]
    + (
        [f"- {c}" for c in checks]
        or ["- within-seed fault maps identical for all three arms; burst steps equal across arms"]
    )
    + [
        "",
        "## Per-seed",
        "",
        "| seed | C frozen | C' living | C'o living-from-original | old A4000 C' eta 0.5 (different fault maps) |",
        "|---|---|---|---|---|",
    ]
)
md += [
    f"| {s} | {R['C'][s]['summary']['final_test_acc']:.2f} | {R['Cp'][s]['summary']['final_test_acc']:.2f} | "
    f"{R['Cpo'][s]['summary']['final_test_acc']:.2f} | {OLD_CP[s]:.2f} |"
    for s in SEEDS
]
md += [
    "",
    "## Comparisons (A minus B, n = 3; labels only, no significance possible)",
    "",
    "| id | A - B | metric | per seed | mean | sd | wins | p_t | p_sign1 | p_wilc | label |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]
md += [
    f"| {r['id']} | {r['a']} - {r['b']} | {r['key']} | {' '.join(f'{x:+.2f}' for x in r['d'])} | {r['mean']:+.2f} | "
    f"{f(r['sd'])} | {r['wins']}/3 | {f(r['p_t'], 3)} | {f(r['p_sign1'], 3)} | {f(r['p_wilc'], 3)} | {r['label']} |"
    for r in rows
]
out = ROOT / "results/derived/living-tuned-results.md"
out.write_text("\n".join(md) + "\n")
print("\n".join(md))
